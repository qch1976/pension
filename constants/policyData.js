function round2(n) { return Math.round(n * 100) / 100; }

function buildMinMonthsTable() {
  var m = {};
  var y;
  for (y = 1949; y <= 2029; y++) m[y] = 180;
  for (y = 2030; y <= 2038; y++) m[y] = 180 + 6 * (y - 2029);
  for (y = 2039; y <= 2100; y++) m[y] = 240;
  return m;
}

